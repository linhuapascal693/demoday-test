import { NextRequest, NextResponse } from 'next/server'
import { chatCompletion } from '@/lib/siliconflow'

// 生成 5W1H 详细分析
export async function POST(request: NextRequest) {
  try {
    const { concept, type, basicContent } = await request.json()

    if (!concept || !type) {
      return NextResponse.json(
        { error: '请提供概念名称和类型' },
        { status: 400 }
      )
    }

    // 根据类型生成不同的提示词
    const prompts: { [key: string]: string } = {
      what: `作为一位资深教育专家，请为「${concept}」的"What（是什么）"维度生成深入细致的分析。

基础定义：${basicContent}

请从以下几个层面展开：
1. **核心定义**：用精准但易懂的语言定义这个概念
2. **本质特征**：提炼出 3-5 个关键特征，每个特征配以简短说明
3. **概念拆解**：将这个概念拆解为组成部分，说明各部分之间的关系
4. **边界澄清**：明确这个概念不是什么，与易混淆概念的区别
5. **认知框架**：给出一个理解这个概念的框架或思维模型

要求：
- 内容要有深度，适合大学生和职场人士阅读
- 使用类比和例子帮助理解
- 避免过于学术化的表达
- 总字数控制在 400-600 字
- 使用 Markdown 格式，适当使用加粗、列表等`,

      why: `作为一位资深教育专家，请为「${concept}」的"Why（为什么）"维度生成深入细致的分析。

基础价值：${basicContent}

请从以下几个层面展开：
1. **核心价值**：掌握这个概念能带来什么具体价值（效率提升、问题解决、认知升级等）
2. **痛点解决**：这个概念解决了什么实际问题或痛点
3. **竞争优势**：掌握这个概念相比不掌握的人有什么优势
4. **应用场景**：在哪些具体场景下这个价值会显现
5. **长期收益**：从职业发展、个人成长角度的长期价值

要求：
- 内容要有说服力，让读者产生学习动力
- 结合实际案例说明
- 避免空洞的口号式表达
- 总字数控制在 400-600 字
- 使用 Markdown 格式，适当使用加粗、列表等`,

      how: `作为一位资深教育专家，请为「${concept}」的"How（怎么用）"维度生成深入细致的分析。

基础方法：${basicContent}

请从以下几个层面展开：
1. **学习路径**：从入门到精通的阶段性学习路径（3-5 个阶段）
2. **实践方法**：具体的实践步骤或方法论
3. **常见误区**：学习或应用过程中容易犯的错误及如何避免
4. **进阶技巧**：掌握基础后的进阶使用技巧
5. **资源推荐**：学习这个概念需要的关键资源或工具

要求：
- 内容要可操作，读者能按图索骥
- 步骤要具体，避免过于抽象
- 结合最佳实践
- 总字数控制在 400-600 字
- 使用 Markdown 格式，适当使用加粗、列表等`,

      when: `作为一位资深教育专家，请为「${concept}」的"When（何时用）"维度生成深入细致的分析。

基础时机：${basicContent}

请从以下几个层面展开：
1. **触发条件**：什么信号或条件出现时应该使用这个概念
2. **发展阶段**：在个人能力发展的哪个阶段最需要这个概念
3. **场景细分**：细分 4-6 个具体使用场景，每个场景说明：
   - 场景描述
   - 为什么这个场景适合使用
   - 使用后的预期效果
4. **时机判断**：如何判断是否是使用这个概念的最佳时机
5. **避免滥用**：什么情况下不应该使用这个概念

要求：
- 场景要具体、真实、可感知
- 帮助读者建立时机敏感度
- 避免过于笼统的描述
- 总字数控制在 400-600 字
- 使用 Markdown 格式，适当使用加粗、列表等`,

      where: `作为一位资深教育专家，请为「${concept}」的"Where（在哪用）"维度生成深入细致的分析。

基础范围：${basicContent}

请从以下几个层面展开：
1. **领域分布**：这个概念在哪些行业/领域最常用（列举 4-6 个）
2. **岗位应用**：哪些具体岗位会用到这个概念，使用程度如何
3. **工具平台**：使用这个概念需要什么样的工具、平台或环境
4. **组织层级**：在组织的哪些层级（执行层、管理层、决策层）使用较多
5. **地域分布**：这个概念在全球或国内的分布情况（如适用）

要求：
- 帮助读者定位这个概念的应用地图
- 具体举例说明
- 避免空泛的描述
- 总字数控制在 400-600 字
- 使用 Markdown 格式，适当使用加粗、列表等`,

      who: `作为一位资深行业研究专家，请为「${concept}」的"Who（谁在主导）"维度生成深入细致的分析，重点聚焦这个领域的先驱者和当前顶尖高手。

基础信息：${basicContent}

请从以下几个层面展开：

1. **领域先驱（Founding Fathers）**：
   - 这个概念/技术的最早提出者或开创者是谁（个人或团队）
   - 他们是在什么背景下提出/创造这个概念的
   - 最初的愿景或目标是什么
   - 他们的核心贡献是什么

2. **早期布道者（Early Adopters）**：
   - 最早将这个概念付诸实践的人或组织
   - 他们在推广过程中扮演了什么角色
   - 有哪些关键的早期应用案例

3. **当前顶尖高手（Current Masters）**：
   - 当今在这个领域最有影响力的 3-5 位专家/领袖（可以是具体人物或代表性角色）
   - 他们的标志性成就或贡献
   - 他们独特的使用方式或方法论
   - 他们的作品、书籍或公开资源（如有）

4. **标杆组织**：
   - 在这个概念应用上最出色的 2-3 家公司/机构
   - 他们是如何将这个概念发挥到极致的
   - 可以学习借鉴的地方

5. **如何追随**：
   - 如果想向这些高手学习，应该从哪里开始
   - 推荐的学习路径或资源

要求：
- 尽可能提及真实的人物、公司或具体案例（如果信息不足，可以描述典型角色）
- 突出这些先驱和高手的独特之处
- 让读者感受到这个领域的传承和发展脉络
- 激发读者向高手学习的动力
- 总字数控制在 500-700 字
- 使用 Markdown 格式，适当使用加粗、列表等`
    }

    const prompt = prompts[type]
    if (!prompt) {
      return NextResponse.json(
        { error: '无效的类型' },
        { status: 400 }
      )
    }

    // 调用 AI 生成内容
    const content = await chatCompletion([
      { role: 'system', content: '你是一位资深的教育内容专家，擅长将复杂概念深入浅出地讲解清楚。你的回答要有深度、有结构、有实用价值。' },
      { role: 'user', content: prompt }
    ])

    return NextResponse.json({
      success: true,
      content,
      type,
      concept
    })

  } catch (error: any) {
    console.error('5W1H Analysis API Error:', error)
    return NextResponse.json(
      { error: error.message || '生成分析失败' },
      { status: 500 }
    )
  }
}
